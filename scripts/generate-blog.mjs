import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const BLOG_DIR = path.join(process.cwd(), "content", "blog");
const OUTPUT_FILE = path.join(process.cwd(), "lib", "posts.ts");

function calculateReadingTime(text) {
  const wordsPerMinute = 200;
  const wordCount = text.trim().split(/\s+/).length;
  const minutes = Math.ceil(wordCount / wordsPerMinute);
  return `${minutes} min read`;
}

function extractHeadings(content) {
  const headingRegex = /^(#{2,3})\s+(.+)$/gm;
  const headings = [];
  let match;
  while ((match = headingRegex.exec(content)) !== null) {
    const level = match[1].length;
    const text = match[2].trim();
    const id = text
      .toLowerCase()
      .replace(/[^\w\s-]/g, "")
      .replace(/\s+/g, "-");
    headings.push({ level, text, id });
  }
  return headings;
}

export function generateBlogRegistry() {
  if (!fs.existsSync(BLOG_DIR)) {
    fs.mkdirSync(BLOG_DIR, { recursive: true });
  }

  const files = fs
    .readdirSync(BLOG_DIR)
    .filter((file) => file.endsWith(".md") || file.endsWith(".mdx"));

  const posts = files
    .map((filename) => {
      const filePath = path.join(BLOG_DIR, filename);
      const fileContent = fs.readFileSync(filePath, "utf-8");
      const { data, content } = matter(fileContent);

      const slug =
        data.slug || filename.replace(/\.(md|mdx)$/, "").toLowerCase();

      return {
        slug,
        title: data.title || "Untitled Post",
        description: data.description || "",
        publishedAt: data.publishedAt || new Date().toISOString().split("T")[0],
        author: data.author || "Fly Air Logistics Editorial Team",
        category: data.category || "Freight Logistics",
        tags: Array.isArray(data.tags) ? data.tags : [],
        readingTime: calculateReadingTime(content),
        headings: extractHeadings(content),
        content,
      };
    })
    .sort(
      (a, b) =>
        new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
    );

  const tsContent = `// Auto-generated by scripts/generate-blog.mjs at build time.
// DO NOT EDIT DIRECTLY. Edit files in content/blog/*.md instead.

export interface BlogHeading {
  level: number;
  text: string;
  id: string;
}

export interface BlogPost {
  slug: string;
  title: string;
  description: string;
  publishedAt: string;
  author: string;
  category: string;
  tags: string[];
  readingTime: string;
  headings: BlogHeading[];
  content: string;
}

export const posts: BlogPost[] = ${JSON.stringify(posts, null, 2)};

export function getAllPosts(): BlogPost[] {
  return posts;
}

export function getPostBySlug(slug: string): BlogPost | undefined {
  return posts.find((p) => p.slug === slug);
}

export function getRecentPosts(limit = 3): BlogPost[] {
  return posts.slice(0, limit);
}

export function getAllPostSlugs(): string[] {
  return posts.map((p) => p.slug);
}
`;

  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, tsContent, "utf-8");
  console.log(`[Blog Generator] Successfully generated ${posts.length} blog posts into ${OUTPUT_FILE}`);
}

generateBlogRegistry();

